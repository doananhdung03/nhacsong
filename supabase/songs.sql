-- Run once in Supabase SQL Editor. Safe to re-run.
create table if not exists public.songs (
  id bigint generated always as identity primary key,
  title text not null check (char_length(title) between 1 and 200),
  artist text not null check (char_length(artist) <= 200),
  initials text not null check (char_length(initials) <= 100),
  folded text not null check (char_length(folded) <= 200),
  key text not null unique check (char_length(key) <= 401),
  created_at timestamptz not null default now()
);
alter table public.songs enable row level security;
drop policy if exists "Anyone can read songs" on public.songs;
create policy "Anyone can read songs" on public.songs for select to anon, authenticated using (true);
-- Single-user project: anyone with the public key may add songs; nobody can update/delete via API.
drop policy if exists "Anyone can add songs" on public.songs;
create policy "Anyone can add songs" on public.songs for insert to anon, authenticated with check (true);
grant select, insert on public.songs to anon, authenticated;

